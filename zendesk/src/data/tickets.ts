function getRandomDate(daysAgo: number): string {
  const date = new Date();
  date.setDate(date.getDate() - daysAgo);
  date.setHours(Math.floor(Math.random() * 24));
  date.setMinutes(Math.floor(Math.random() * 60));
  return date.toISOString();
}

function calculateSLAStatus(createdAt: string, priority: string, firstResponseAt?: string): { slaStatus: 'active' | 'breached' | 'at_risk', slaBreachTime?: string } {
  const created = new Date(createdAt).getTime();
  const now = Date.now();
  const elapsed = (now - created) / 60000; // minutes

  const slaLimits: Record<string, number> = {
    urgent: 15,
    high: 30,
    normal: 60,
    low: 120,
  };

  const limit = slaLimits[priority] || 60;
  const breachTime = new Date(created + limit * 60000).toISOString();

  if (!firstResponseAt && elapsed > limit) {
    return { slaStatus: 'breached', slaBreachTime: breachTime };
  } else if (!firstResponseAt && elapsed > limit * 0.75) {
    return { slaStatus: 'at_risk', slaBreachTime: breachTime };
  }
  return { slaStatus: 'active', slaBreachTime: breachTime };
}

